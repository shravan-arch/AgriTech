export const getTranslation = (lang, key, params = {}) => {
  const selectedLang = translations[lang] ? lang : 'en';
  const keys = key.split('.');
  let current = translations[selectedLang];

  for (const part of keys) {
    if (current && typeof current === 'object' && part in current) {
      current = current[part];
    } else {
      current = null;
      break;
    }
  }

  // Fallback to English if missing in selected language
  if (!current && selectedLang !== 'en') {
    let fallback = translations.en;
    for (const part of keys) {
      if (fallback && typeof fallback === 'object' && part in fallback) {
        fallback = fallback[part];
      } else {
        fallback = null;
        break;
      }
    }
    current = fallback;
  }

  if (typeof current !== 'string') {
    return key;
  }

  // Replace {param} placeholders
  return current.replace(/\{(\w+)\}/g, (_, placeholder) => {
    return params[placeholder] !== undefined ? params[placeholder] : `{${placeholder}}`;
  });
};

export default translations;
